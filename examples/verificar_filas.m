% Comprobaciones geométricas sin toolboxes ni acceso a Internet.
root=fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(root,'src'));
p=struct('lat',40,'lon',-5,'alpha',0,'beta',30,'W',10,'L',2,'n',3,'h',.3);
m=pv_filas_modelo(p,datetime(2026,12,21),[9 10.5 12 13.5 15]);
assert(abs(m.d-2.15828)<1e-4);
assert(max(m.fraccion(2:4,:),[],'all')<1e-8);
assert(any(m.fraccion([1 5],:)>0,'all'));
assert(abs(m.LCR-.44523)<1e-4);
p.beta=0;m=pv_filas_modelo(p,datetime(2026,12,21),12);
assert(m.d==0 && m.LCR==1 && all(m.fraccion==0));
p.beta=30;p.alpha=-30;
a=pv_filas_modelo(p,datetime(2026,12,21),[9 15]);
p.alpha=30;b=pv_filas_modelo(p,datetime(2026,12,21),[15 9]);
assert(abs(a.d-b.d)<1e-12);
assert(max(abs(a.fraccion-b.fraccion),[],'all')<1e-8);
p.n=1;m=pv_filas_modelo(p,datetime(2026,6,21),[6 12 18]);
assert(all(m.fraccionGeometrica==0,'all'));
p.alpha=0;p.n=3;
summer=pv_filas_modelo(p,datetime(2026,7,21),[12 18.86 0]);
assert(summer.incidencia(1)>0 && ~summer.posterior(1));
assert(summer.alt(2)>0 && summer.incidencia(2)<0 && summer.posterior(2));
assert(abs(summer.incidencia(2)+8.4)<.1);
assert(all(summer.fraccion(2,:)==1));
assert(isnan(summer.incidencia(3)) && all(isnan(summer.fraccion(3,:))));
f=pv_filas_visualizador('off');
assert(~isempty(findall(f,'Type','axes')));
mode=findall(f,'Tag','referenciaHoraria');
mode.Value='Hora civil';feval(mode.ValueChangedFcn,mode,[]);
labels=findall(f,'Type','uilabel');
assert(~any(arrayfun(@(x) any(contains(string(x.Text),'Unrecognized'),'all'),labels)));
delete(f);
d=datetime(2026,12,21);civil=pv_hora_solar(d,-5,12,'solarToCivil');
assert(civil>13 && civil<14);
assert(abs(pv_hora_solar(d,-5,civil,'civilToSolar')-12)<1e-8);
summer=pv_hora_solar(datetime(2026,6,21),-5,12,'solarToCivil');
assert(summer>14 && summer<15);
assert(max(abs(pv_hora_solar(d,-5,0:.25:24,'civilToSolar')-(0:.25:24)-(12-civil)))<1e-8);
disp('Visualizador y geometría: verificaciones correctas.');
